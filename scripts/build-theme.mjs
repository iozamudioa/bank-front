import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
// Reuse the builder's esbuild; this adds no project dependency.
const { build } = require(
  require.resolve('esbuild', { paths: [require.resolve('@angular/build/package.json')] }),
);
await build({
  entryPoints: ['src/app/core/theme/theme-bootstrap.ts'],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  outfile: 'public/theme-init.js',
  legalComments: 'none',
  banner: { js: '// Generated by npm run theme:generate. Do not edit.' },
});
console.log('Theme bootstrap generated from the shared palette catalog.');
