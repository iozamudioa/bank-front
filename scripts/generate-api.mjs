function type(s = {}) {
  let t =
    ref(s) ||
    (s.oneOf
      ? '(' + s.oneOf.map(type).join(' | ') + ')'
      : s.anyOf
        ? '(' + s.anyOf.map(type).join(' | ') + ')'
        : s.allOf
          ? '(' + s.allOf.map(type).join(' & ') + ')'
          : s.enum
            ? [...new Set(s.enum)].map(JSON.stringify).join(' | ')
            : s.type === 'array'
              ? `(${type(s.items)})[]`
              : s.type === 'object'
                ? s.additionalProperties
                  ? `Record<string, ${s.additionalProperties === true ? 'unknown' : type(s.additionalProperties)}>`
                  : `{ ${Object.entries(s.properties || {})
                      .map(([k, v]) => `${k}${s.required?.includes(k) ? '' : '?'}: ${type(v)}`)
                      .join('; ')} }`
                : { integer: 'number', number: 'number', boolean: 'boolean', string: 'string' }[
                    s.type
                  ] || 'unknown');
  return t + (s.nullable ? ' | null' : '');
}
